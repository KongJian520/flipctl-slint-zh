//! Generates the crate's themes from tokens.toml, its copy from locales/*.toml, and
//! compiles the components.
//!
//! The generators live in flipper-tokens, so a hosted app's build produces the
//! same theme from the same parse of the same file.

use std::{env, fs, path::PathBuf};

use flipper_tokens::{parse, rust_theme, slint_theme, write_if_changed};

fn main() {
    println!("cargo:rerun-if-changed=tokens.toml");

    let doc = parse(&fs::read_to_string("tokens.toml").expect("tokens.toml"));

    let out = PathBuf::from(env::var_os("OUT_DIR").expect("OUT_DIR"));
    write_if_changed(&out.join("theme.rs"), &rust_theme(&doc));
    let theme_slint = out.join("theme.slint");
    write_if_changed(&theme_slint, &slint_theme(&doc));

    i18n(&out);

    #[cfg(feature = "screens")]
    compile_slint(&theme_slint);
}

/// One locale: `locale`, `name` and its `"id" = "text"` entries.
///
/// A hand-rolled reader rather than a TOML dependency, for the same reason
/// flipper-tokens has one: the file this parses is the file we write, and the shapes
/// it must accept are a handful of lines, not the language.
struct Locale {
    id: String,
    name: String,
    texts: Vec<(String, String)>,
}

fn read_locales(dir: &std::path::Path) -> Vec<Locale> {
    let mut found = Vec::new();
    let mut paths: Vec<PathBuf> = fs::read_dir(dir)
        .expect("locales/")
        .filter_map(|e| e.ok().map(|e| e.path()))
        .filter(|p| p.extension().is_some_and(|x| x == "toml"))
        .collect();
    paths.sort();
    for path in paths {
        let text = fs::read_to_string(&path).expect("a locale file");
        let (mut id, mut name, mut texts) = (String::new(), String::new(), Vec::new());
        for line in text.lines() {
            let line = line.trim();
            if line.is_empty() || line.starts_with('#') {
                continue;
            }
            let Some((key, value)) = line.split_once('=') else { continue };
            let (key, value) = (key.trim(), unquote(value.trim()));
            match key {
                "locale" => id = value,
                "name" => name = value,
                _ => texts.push((unquote(key), value)),
            }
        }
        assert!(!id.is_empty(), "{} has no `locale`", path.display());
        texts.sort();
        found.push(Locale { id, name, texts });
    }
    found
}

fn unquote(text: &str) -> String {
    text.trim_matches('"').replace("\\\"", "\"")
}

/// Generate `i18n_generated.rs` from `locales/*.toml`.
///
/// The point of doing it here rather than at runtime is the check in the middle: a
/// locale that is missing a line, or that invents one, fails the build with the id
/// named. A gap that only shows up as a row of English on the panel is a gap nobody
/// notices until a customer does.
fn i18n(out: &std::path::Path) {
    println!("cargo:rerun-if-changed=locales");
    let locales = read_locales(&std::path::Path::new("locales"));
    assert!(!locales.is_empty(), "locales/ is empty");
    let source = locales
        .iter()
        .position(|l| l.id == "en")
        .expect("an `en` locale, which is the fallback");

    for locale in &locales {
        for (key, _) in &locales[source].texts {
            if !locale.texts.iter().any(|(k, _)| k == key) {
                panic!("{}: locale `{}` has no text for `{key}`", locale.id, locale.id);
            }
        }
        for (key, _) in &locale.texts {
            if !locales[source].texts.iter().any(|(k, _)| k == key) {
                panic!("locale `{}` has `{key}`, which en does not", locale.id);
            }
        }
    }

    let mut out_text = String::from(
        "// @generated by build.rs from locales/*.toml. Do not edit.\n\n\
         /// One language the panel can draw.\n\
         pub struct Locale {\n    /// The value in `FLIPCTL_LANG` and the locale file's name.\n    pub id: &'static str,\n    /// What the Settings row shows.\n    pub name: &'static str,\n}\n\n",
    );
    out_text.push_str("/// Every locale the build found, `en` first.\npub static LOCALES: &[Locale] = &[\n");
    for locale in &locales {
        out_text.push_str(&format!(
            "    Locale {{ id: {:?}, name: {:?} }},\n",
            locale.id, locale.name
        ));
    }
    out_text.push_str("];\n\n/// Each locale's texts, in the same order as `LOCALES`, sorted by id.\npub static TEXTS: &[&[(&str, &str)]] = &[\n");
    for locale in &locales {
        out_text.push_str("    &[\n");
        for (key, value) in &locale.texts {
            out_text.push_str(&format!("        ({key:?}, {value:?}),\n"));
        }
        out_text.push_str("    ],\n");
    }
    out_text.push_str("];\n");
    write_if_changed(&out.join("i18n_generated.rs"), &out_text);
}

/// Compile the .slint components against the generated theme.
///
/// `EmbedFiles` embeds the TTFs as they are and decodes them at runtime, which is
/// what a language with more than ninety-five glyphs needs: `EmbedForSoftwareRenderer`
/// bakes only the characters a `.slint` literal contains, so a Wi-Fi name could never
/// be drawn. The fonts stay embedded either way — nothing is installed into
/// /usr/share/fonts and no fontconfig rule is involved.
///
/// SLINT_FONT_SIZES is pinned to 16 and must stay there: the FlipCTL fonts are
/// pixel fonts on a 64-unit design-pixel grid at 1024 units/em, so they
/// rasterise with zero partial coverage at 16px and antialias at anything else.
#[cfg(feature = "screens")]
fn compile_slint(theme: &std::path::Path) {
    println!("cargo:rerun-if-changed=ui");

    std::env::set_var("SLINT_FONT_SIZES", "16");

    let mut libs = std::collections::HashMap::new();
    libs.insert("theme".to_string(), theme.to_path_buf());

    let config = slint_build::CompilerConfiguration::new()
        .embed_resources(slint_build::EmbedResourcesKind::EmbedFiles)
        .with_library_paths(libs);

    slint_build::compile_with_config("ui/screens.slint", config).expect("compile ui/screens.slint");
}
